-- Owned fresh schema. Existing integrations must match ALL consumed column types.
-- Execute using a local migration operator, never a runtime app role.
DO $$
DECLARE r record;
BEGIN
 FOR r IN SELECT * FROM (VALUES ('ip_intel_read'),('ip_intel_reputation'),('ip_intel_auth'),('ip_intel_maintenance')) v(name) LOOP
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname=r.name) THEN
   EXECUTE format('CREATE ROLE %I NOLOGIN',r.name);
  END IF;
 END LOOP;
 IF (to_regclass('public.ip_intel_cache') IS NULL) <> (to_regclass('public.ip_intel_events') IS NULL) THEN
  RAISE EXCEPTION 'Incompatible telemetry schema: cache and events must both exist or both be absent; map external integration explicitly';
 END IF;
END $$;
CREATE TABLE IF NOT EXISTS ip_intel_cache (
 ip text PRIMARY KEY, first_seen timestamptz NOT NULL, last_seen timestamptz NOT NULL,
 last_alert_id text, reputation_source text, abuse_score integer, vt_malicious integer,
 country_code text, isp text, geo_json jsonb, reputation_json jsonb,
 attack_types text[] NOT NULL DEFAULT '{}', mitre_tactics text[] NOT NULL DEFAULT '{}',
 target_hosts text[] NOT NULL DEFAULT '{}', endpoints_targeted text[] NOT NULL DEFAULT '{}',
 http_methods_used text[] NOT NULL DEFAULT '{}', total_alert_count integer NOT NULL DEFAULT 0,
 notes text, reputation_checked_at timestamptz
);
CREATE TABLE IF NOT EXISTS ip_intel_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ip text NOT NULL REFERENCES ip_intel_cache(ip) ON DELETE RESTRICT,
 seen_at timestamptz NOT NULL, alert_type text, attack_subtype text,
 mitre text[] NOT NULL DEFAULT '{}', target_host text, endpoint text, outcome text, raw_summary text
);
DO $$
DECLARE r record; actual text;
BEGIN
 FOR r IN SELECT * FROM (VALUES
 ('ip_intel_cache','ip','text'),('ip_intel_cache','first_seen','timestamp with time zone'),
 ('ip_intel_cache','last_seen','timestamp with time zone'),('ip_intel_cache','last_alert_id','text'),
 ('ip_intel_cache','reputation_source','text'),('ip_intel_cache','abuse_score','integer'),
 ('ip_intel_cache','vt_malicious','integer'),('ip_intel_cache','country_code','text'),
 ('ip_intel_cache','isp','text'),('ip_intel_cache','geo_json','jsonb'),('ip_intel_cache','reputation_json','jsonb'),
 ('ip_intel_cache','attack_types','ARRAY'),('ip_intel_cache','mitre_tactics','ARRAY'),
 ('ip_intel_cache','target_hosts','ARRAY'),('ip_intel_cache','endpoints_targeted','ARRAY'),
 ('ip_intel_cache','http_methods_used','ARRAY'),('ip_intel_cache','total_alert_count','integer'),
 ('ip_intel_cache','notes','text'),('ip_intel_cache','reputation_checked_at','timestamp with time zone'),
 ('ip_intel_events','id','bigint'),('ip_intel_events','ip','text'),('ip_intel_events','seen_at','timestamp with time zone'),
 ('ip_intel_events','alert_type','text'),('ip_intel_events','attack_subtype','text'),('ip_intel_events','mitre','ARRAY'),
 ('ip_intel_events','target_host','text'),('ip_intel_events','endpoint','text'),('ip_intel_events','outcome','text'),('ip_intel_events','raw_summary','text')
 ) v(tbl,col,typ) LOOP
  SELECT data_type INTO actual FROM information_schema.columns WHERE table_schema='public' AND table_name=r.tbl AND column_name=r.col;
  IF actual IS DISTINCT FROM r.typ OR (r.typ='ARRAY' AND NOT EXISTS (
   SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name=r.tbl AND column_name=r.col AND udt_name='_text'
  )) THEN
   RAISE EXCEPTION 'Incompatible telemetry schema: %.% expected %. Stop and map the integration explicitly; no existing column was altered.',r.tbl,r.col,r.typ;
  END IF;
 END LOOP;
END $$;
CREATE TABLE IF NOT EXISTS ip_intel_reputation (
 ip text PRIMARY KEY, abuse_score integer CHECK (abuse_score BETWEEN 0 AND 100), country_code text,
 isp text, geo_json jsonb, reputation_json jsonb, reputation_checked_at timestamptz,
 revision bigint NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS ip_intel_schema_migrations (version text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());
